"""Writes the app's copy of the public style catalog (no prompt text).

    python scripts/export_public_catalog.py          # write
    python scripts/export_public_catalog.py --check  # exit 1 if out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from styleapi.catalog import public_catalog_json  # noqa: E402

TARGET = ROOT.parent / "mobile" / "src" / "styles" / "catalog.generated.ts"

HEADER = """// GENERATED by apps/style-api/scripts/export_public_catalog.py from apps/style-api/styleapi/catalog.json.
// Do not edit. Public fields only: prompts stay on the server.
import type { PublicCatalog } from './types';

export const CATALOG: PublicCatalog = """


def render() -> str:
    return HEADER + public_catalog_json() + ";\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != content:
            print(f"{TARGET} is out of date; run scripts/export_public_catalog.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(content)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
